"""Generate the accent-folding table used by both implementations (Python and .NET).

The table is written as source code into both packages so neither depends on Unicode
normalization at run time (which behaves differently across runtimes and in .NET's
invariant-globalization mode). Run from the repository root:  python tools/make_fold_table.py
"""
import unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SPECIAL = {"ß": "ss", "æ": "ae", "Æ": "ae", "œ": "oe", "Œ": "oe", "ø": "o", "Ø": "o", "ð": "d", "Ð": "d",
           "þ": "th", "Þ": "th", "ł": "l", "Ł": "l", "đ": "d", "Đ": "d", "ħ": "h", "Ħ": "h", "ı": "i",
           "ĸ": "k", "ŉ": "n", "ŋ": "n", "Ŋ": "n", "ſ": "s", "ƒ": "f", "ª": "a", "º": "o"}


def build():
    table = {}
    for cp in list(range(0x00C0, 0x0250)) + [0x00AA, 0x00BA]:
        ch = chr(cp)
        if ch in SPECIAL:
            table[ch] = SPECIAL[ch]
            continue
        if ch in ("×", "÷"):
            continue
        base = unicodedata.normalize("NFKD", ch)
        base = "".join(c for c in base if not unicodedata.combining(c))
        if base and all("a" <= c.lower() <= "z" for c in base):
            table[ch] = base.lower()
    return dict(sorted(table.items()))


def main():
    table = build()
    py = ["# Generated by tools/make_fold_table.py. Do not edit.", "FOLD = {"]
    py += [f"    {k!r}: {v!r}," for k, v in table.items()]
    py.append("}")
    (ROOT / "python" / "src" / "dedupkit_br" / "_fold.py").write_text("\n".join(py) + "\n", encoding="utf-8")
    cs = ["// Generated by tools/make_fold_table.py. Do not edit.", "namespace DedupKit;", "",
          "internal static class FoldTable", "{",
          "    internal static readonly IReadOnlyDictionary<char, string> Fold = new Dictionary<char, string>", "    {"]
    cs += [f"        ['\\u{ord(k):04X}'] = \"{v}\"," for k, v in table.items()]
    cs += ["    };", "}"]
    out = ROOT / "dotnet" / "src" / "DedupKit" / "FoldTable.cs"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(cs) + "\n", encoding="utf-8")
    print(len(table), "characters")


if __name__ == "__main__":
    main()
